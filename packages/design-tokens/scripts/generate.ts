import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  darkSemanticTokens,
  foundationTokens,
  lightSemanticTokens,
  tailwindThemeTokens,
  type CssTokenMap,
} from '../src/tokens'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const generatedDir = resolve(packageRoot, 'generated')

function declarations(tokens: CssTokenMap, indentation = '  '): string {
  return Object.entries(tokens)
    .map(([name, value]) => `${indentation}--${name}: ${value};`)
    .join('\n')
}

function themeBlock(): string {
  return `@theme inline {\n${declarations(tailwindThemeTokens)}\n}`
}

export function renderWebCss(): string {
  return `/* Generated by scripts/generate.ts. Do not edit directly. */
:root {
${declarations({ ...lightSemanticTokens, ...foundationTokens })}
}

${themeBlock()}

.dark {
  color-scheme: dark;
${declarations(darkSemanticTokens)}
}
`
}

export function renderNativewindCss(): string {
  return `/* Generated by scripts/generate.ts. Do not edit directly. */
:root {
${declarations({ ...lightSemanticTokens, ...foundationTokens })}
}

${themeBlock()}

@media (prefers-color-scheme: dark) {
  :root {
${declarations(darkSemanticTokens, '    ')}
  }
}
`
}

const files = {
  'web.css': renderWebCss(),
  'nativewind.css': renderNativewindCss(),
} as const

if (process.argv.includes('--stdout')) {
  process.stdout.write(`${files['web.css']}\n--- nativewind.css ---\n${files['nativewind.css']}`)
} else if (process.argv.includes('--check')) {
  let stale = false
  for (const [name, contents] of Object.entries(files)) {
    const path = resolve(generatedDir, name)
    if (!existsSync(path) || readFileSync(path, 'utf8') !== contents) {
      console.error(`${name} is stale; run bun run generate`)
      stale = true
    }
  }
  if (stale) process.exit(1)
} else {
  for (const [name, contents] of Object.entries(files)) {
    writeFileSync(resolve(generatedDir, name), contents)
  }
}
