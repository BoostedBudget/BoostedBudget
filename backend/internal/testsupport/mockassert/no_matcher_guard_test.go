// countNoMatcherAssertNotCalled returns the line numbers of every `AssertNotCalled` call with
// exactly two arguments — the receiver-method form `m.AssertNotCalled(t, "Name")` and the
// package-function form both land here, because both are a call whose second argument is the method
// name and which supplies no matchers.
//
// Two arguments is the whole criterion, and it is deliberately syntactic. A call WITH matchers
// (`AssertNotCalled(t, "Name", mock.Anything)`) is a real assertion and is not this guard's
// business; a call with a variadic slice spread is left alone for the same reason.
func countNoMatcherAssertNotCalled(filename string, src []byte) ([]int, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, src, 0)
	if err != nil {
		return nil, fmt.Errorf("parsing %s: %w", filename, err)
	}
	var lines []int
	ast.Inspect(file, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok || len(call.Args) != 2 {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != "AssertNotCalled" {
			return true
		}
		// The second argument must be the method NAME, i.e. a string literal. `AssertNotCalled(t, x)`
		// with a computed name is not the shape this guard is about.
		lit, ok := call.Args[1].(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			return true
		}
		lines = append(lines, fset.Position(call.Pos()).Line)
		return true
	})
	return lines, nil
}

// TestNoNewNoMatcherAssertNotCalled is the ratchet.
func TestNoNewNoMatcherAssertNotCalled(t *testing.T) {
	// Repo root: backend/internal/testsupport/mockassert -> ... -> repo root.
	const repoRoot = "../../../.."

	files, err := sourcefiles.Union(repoRoot, "backend", sourcefiles.HasExt("_test.go"))
	if err != nil {
		t.Fatalf("listing backend tests: %v — this guard must fail closed rather than scan nothing", err)
	}

	found := map[string]int{}
	where := map[string][]int{}
	scanned := 0
	for _, rel := range files {
		src, readErr := os.ReadFile(filepath.Join(repoRoot, rel))
		if readErr != nil {
			t.Fatalf("reading %s: %v", rel, readErr)
		}
		scanned++
		lines, parseErr := countNoMatcherAssertNotCalled(rel, src)
		if parseErr != nil {
			t.Fatalf("%v", parseErr)
		}
		if len(lines) > 0 {
			found[rel] = len(lines)
			where[rel] = lines
		}
	}

	// Fail closed: a scan of nothing would pass vacuously and read as protection.
	if scanned == 0 {
		t.Fatalf("scanned no _test.go files at all — the walk is broken")
	}
	if len(found) == 0 && len(noMatcherBaseline) > 0 {
		t.Fatalf("scanned %d test files and found zero no-matcher AssertNotCalled calls, but %d files "+
			"are baselined — the scan is broken", scanned, len(noMatcherBaseline))
	}

	var added, reduced []string
	for rel, n := range found {
		base, ok := noMatcherBaseline[rel]
		switch {
		case !ok:
			added = append(added, fmt.Sprintf("%s: %d new (lines %v)", rel, n, where[rel]))
		case n > base:
			added = append(added, fmt.Sprintf("%s: %d, baseline %d (lines %v)", rel, n, base, where[rel]))
		case n < base:
			reduced = append(reduced, fmt.Sprintf("%s: %d, baseline %d", rel, n, base))
		}
	}
	for rel, base := range noMatcherBaseline {
		if _, ok := found[rel]; !ok {
			reduced = append(reduced, fmt.Sprintf("%s: 0, baseline %d — delete the entry", rel, base))
		}
	}
	sort.Strings(added)
	sort.Strings(reduced)

	if len(added) > 0 {
		t.Errorf("%d file(s) gained a no-matcher AssertNotCalled (#1569).\n"+
			"`AssertNotCalled(t, \"Method\")` with no argument matchers asserts that the method was "+
			"never called with an EMPTY argument list. For a method that takes arguments that can "+
			"never fail — the assertion passes while the call is happening.\n"+
			"Use `mockassert.NoCallTo(t, &theMock.Mock, \"Method\")` instead:\n    %s",
			len(added), strings.Join(added, "\n    "))
	}
	if len(reduced) > 0 {
		t.Errorf("%d file(s) are BELOW their baseline — good, now lock it in by lowering the number "+
			"in noMatcherBaseline (or deleting the entry). Leaving the baseline high lets the next "+
			"new one in for free:\n    %s", len(reduced), strings.Join(reduced, "\n    "))
	}
}

