// TestNoMatcherGuard_FlagsTheNoOpForm is the case the guard exists for, and its neighbours: the form
// WITH matchers is a real assertion and must not be flagged, or the guard becomes noise and the
// baseline gets raised to silence it.
func TestNoMatcherGuard_FlagsTheNoOpForm(t *testing.T) {
	cases := []struct {
		name string
		body string
		want int
	}{
		{"no matchers — the no-op", `m.AssertNotCalled(t, "Save")`, 1},
		{"one matcher is a real assertion", `m.AssertNotCalled(t, "Save", mock.Anything)`, 0},
		{"three matchers", `m.AssertNotCalled(t, "Save", mock.Anything, mock.Anything, mock.Anything)`, 0},
		{"the helper is not flagged", `mockassert.NoCallTo(t, &m.Mock, "Save")`, 0},
		{"AssertCalled is a different assertion", `m.AssertCalled(t, "Save")`, 0},
		{"computed name is out of scope", `m.AssertNotCalled(t, name)`, 0},
		{"two on one line both count", `m.AssertNotCalled(t, "A"); m.AssertNotCalled(t, "B")`, 2},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			src := []byte("package x\nfunc f() {\n\t" + tc.body + "\n}\n")
			lines, err := countNoMatcherAssertNotCalled("x.go", src)
			if err != nil {
				t.Fatal(err)
			}
			if len(lines) != tc.want {
				t.Fatalf("got %d (%v), want %d", len(lines), lines, tc.want)
			}
		})
	}
}

// TestNoMatcherGuard_MultilineCallIsStillSeen is the case a grep-based guard misses. gofmt will
// wrap a long call, and a line-oriented scan then sees an opening paren and nothing else.
func TestNoMatcherGuard_MultilineCallIsStillSeen(t *testing.T) {
	src := []byte(`package x
func f() {
	someVeryLongMockVariableName.AssertNotCalled(
		t,
		"MethodWithAnExtremelyLongName",
	)
}
`)
	lines, err := countNoMatcherAssertNotCalled("x.go", src)
	if err != nil {
		t.Fatal(err)
	}
	if len(lines) != 1 {
		t.Fatalf("a wrapped call must still be reported, got %v", lines)
	}
}

// TestNoMatcherGuard_BaselineIsNotEmpty guards the guard. An empty baseline map, combined with the
// tree happening to contain none, is a green test that means nothing; and a baseline that someone
// clears to "fix" a failure removes the ratchet entirely.
func TestNoMatcherGuard_BaselineIsNotEmpty(t *testing.T) {
	if len(noMatcherBaseline) == 0 {
		t.Fatal("noMatcherBaseline is empty — either every call was fixed (delete this test and the " +
			"baseline, and make the guard a flat ban) or the ratchet has been disabled")
	}
	total := 0
	for _, n := range noMatcherBaseline {
		total += n
	}
	if total > 352 {
		t.Fatalf("the baseline total is %d, above the 352 recorded when this guard was written; the "+
			"ratchet only turns one way", total)
	}
}

// ---- The defect itself, demonstrated. ----------------------------------------------------------

// fakeTestingT implements testify's mock.TestingT, which — unlike *testing.T — can be substituted,
// so an assertion's PASS/FAIL verdict can be observed instead of being acted on.
type fakeTestingT struct{ failed bool }

func (f *fakeTestingT) Logf(string, ...interface{})   {}
func (f *fakeTestingT) Errorf(string, ...interface{}) { f.failed = true }
func (f *fakeTestingT) FailNow()                      { f.failed = true }

// TestAssertNotCalledWithNoMatchersCannotFail is the reason this whole file exists, demonstrated
// rather than asserted in a comment. A mock records a real call to Save("x"), and testify's
// AssertNotCalled(t, "Save") — the form 351 call sites in this tree still use — reports PASS.
//
// If testify ever changes this behaviour, this test goes red and the guard above can be deleted.
func TestAssertNotCalledWithNoMatchersCannotFail(t *testing.T) {
	m := &mock.Mock{}
	m.Test(t)
	m.On("Save", "x").Return(nil)
	m.MethodCalled("Save", "x")

	spy := &fakeTestingT{}
	passed := m.AssertNotCalled(spy, "Save")

	if !passed || spy.failed {
		t.Fatalf("testify's behaviour has changed: AssertNotCalled(t, \"Save\") now fails on a "+
			"recorded call (passed=%v failed=%v). The no-matcher form is no longer a no-op, and this "+
			"guard plus NoCallTo can be reconsidered.", passed, spy.failed)
	}

	// And the replacement sees it.
	if _, called := firstCallTo(m, "Save"); !called {
		t.Fatal("firstCallTo must see the call that AssertNotCalled cannot")
	}
}

// TestNoCallTo_DecisionIsOnTheMethodNameAlone pins that NoCallTo ignores arguments entirely, which
// is what makes it survive a signature change that would silently break a matcher list.
func TestNoCallTo_DecisionIsOnTheMethodNameAlone(t *testing.T) {
	m := &mock.Mock{}
	m.Test(t)
	m.On("Save", "a", 1).Return(nil)
	m.MethodCalled("Save", "a", 1)

	args, called := firstCallTo(m, "Save")
	if !called {
		t.Fatal("a recorded call must be found regardless of its arguments")
	}
	if len(args) != 2 {
		t.Fatalf("the reported arguments are what makes the failure message useful, got %v", args)
	}
	if _, called := firstCallTo(m, "Load"); called {
		t.Fatal("a method that was never called must not be reported")
	}
}
