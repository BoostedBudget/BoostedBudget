// Issue #1569 task 21, item D — the mechanical half of "a closed account carries no balance".
//
// THE RULE. In non-test Go under backend/internal, an account-shaped SELECT (one whose select list
// names `plaid_account_id` — the same marker TestNoAccountProjectionOmitsStatus uses, and for the
// same reasons) may not name `current_balance` or `available_balance` except through
// accountBalanceProjection. A bare `a.current_balance` in an account projection hands the caller a
// figure frozen at the moment the account stopped syncing, with nothing to say it is stale.
//
// WHY A GUARD RATHER THAN TRUST. The failure is invisible by construction: a stale balance is a
// well-formed number in the right column. Nothing about it looks wrong in a code review, in a
// response body, or on screen. It is only wrong in the sense that it is not true any more — and
// that is precisely the class of defect that survives review, which is why the ruling gets a
// checker instead of a convention.
//
// WHY IT IS EXACT AND NOT A HEURISTIC. This test lives in package `repository`, so it calls
// accountBalanceProjection itself. The text it strips is the text the production query contains,
// generated by the same function — there is no restatement to drift.
//
// PER SELECT LIST. Same lesson as the sibling guards: an aggregated per-file or per-function check
// is satisfied by a neighbouring compliant query, which is the bug.
//
// WHAT IT CANNOT SEE, stated rather than discovered later:
//
//  1. It inherits every blind spot of the `plaid_account_id` marker — a `SELECT *`, or a narrow
//     read that pulls `current_balance` without the marker, is invisible. FOUR such reads exist
//     today, all in investment_analytics_repository.go (lines 98, 115, 205, 221 at the time of
//     writing): they select `a.current_balance` in an aggregate over `accounts a` without ever
//     naming `plaid_account_id`. They are correct — but by a DIFFERENT mechanism, the
//     `currentStateAccountLeg("a")` in their WHERE, which restricts them to active accounts and
//     which this guard cannot see. If that leg were removed those reads would surface a terminal
//     account's frozen balance and nothing here would fire. That is a real hole, named rather than
//     glossed; closing it wants a marker for "reads a balance from accounts", not a wider version
//     of this one.
//  2. It governs the `accounts` table only. A balance selected from balance_snapshots is HISTORY
//     and is deliberately untouched — that is the seam the whole ruling turns on.
//  3. It cannot tell whether the CASE's predicate is RIGHT, only that the fragment is verbatim.
//     The behavioural half is TestAccountRepository_TerminalAccount_CarriesNoCurrentBalance_Integration,
//     which asserts nil out of nine named reads against a real closed account.
//
// Mutation-checked: restoring a bare `a.current_balance, a.available_balance` at any one projection
// turns this red naming the file, line and select list; see task-21-report.md.

// accountBalanceColumn matches either balance column, qualified or not.
var accountBalanceColumn = regexp.MustCompile(`(?i)(?:\b[A-Za-z_][A-Za-z0-9_]*\.)?\b(?:current|available)_balance\b`)

func TestNoAccountProjectionCarriesATerminalBalance(t *testing.T) {
	root := repoInternalRoot(t)

	var offenders []string
	guardedProjections := 0

	err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		fset := token.NewFileSet()
		file, parseErr := parser.ParseFile(fset, path, nil, 0)
		if parseErr != nil {
			return parseErr
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)

		for _, expr := range sqlStringExprs(file) {
			if !containsAccountProjectionMarker(expr.SQL) {
				continue
			}
			for _, m := range accountProjectionSelect.FindAllStringSubmatch(expr.SQL, -1) {
				list := m[1]
				if accountProjectionMarker.FindStringSubmatch(list) == nil {
					continue
				}
				stripped := accountBalanceProjectionFragment.ReplaceAllString(list, " ")
				if strings.EqualFold(stripped, list) && !accountBalanceColumn.MatchString(list) {
					// An account projection that selects no balance at all is fine and is not
					// counted — counting it would let the floor below be met by reads that the
					// rule does not even apply to.
					continue
				}
				if bare := accountBalanceColumn.FindAllString(stripped, -1); len(bare) > 0 {
					offenders = append(offenders,
						rel+":"+strconv.Itoa(fset.Position(expr.Pos).Line)+" ("+strings.Join(bare, ", ")+")"+
							"\n      SELECT "+strings.Join(strings.Fields(list), " ")+" FROM ...")
					continue
				}
				guardedProjections++
			}
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walking internal/: %v", err)
	}

	sort.Strings(offenders)
	if len(offenders) > 0 {
		t.Fatalf("%d account projection(s) select a raw balance column (#1569 task 21, item D).\n"+
			"A terminal-status account's accounts.current_balance is frozen at the moment it stopped "+
			"syncing: it is not what the account holds, and it carries no as-of instant that would "+
			"make it history. The ruling is that a closed account presents NO balance.\n"+
			"Render both columns through accountBalanceProjection(alias) — see account_liveness_sql.go. "+
			"Historical balances belong in balance_snapshots / holding_snapshots and are untouched by "+
			"this rule:\n    %s", len(offenders), strings.Join(offenders, "\n    "))
	}

	// Fail closed. If the folding, the marker or the fragment regex breaks, this guard would examine
	// nothing and report success — which is the failure mode it exists to prevent, applied to itself.
	if guardedProjections < 10 {
		t.Fatalf("this guard checked only %d account balance projection(s) under %s; there are ten, "+
			"so the scan is broken and passing means nothing", guardedProjections, root)
	}
}
