package repository

// Issue #1569 Task 20 (A2). Integration coverage for the THIRD removal cause, 'link_removed' —
// this product removed the account's Plaid Item, so it can never sync again even though the bank
// still reports it.
//
// pgxmock cannot answer any of the three questions here. Whether migration 000167's widened
// accounts_removed_reason_valid actually ADMITS the value, whether the pre-000167 constraint would
// have REJECTED it (which is what makes the migration load-bearing rather than decorative), and
// whether RestoreAccount refuses it are all facts about the live schema.

import (
	"context"
	"fmt"
	"testing"
	"time"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/maxnussbaum/BoostedBudget/internal/domain"
)

// The accounts under a linked item removed by one of this product's own flows must end up
// 'removed', with removed_at stamped and removed_reason = 'link_removed'.
//
// removed_at is asserted only for PRESENCE and for being finite — never compared against a Go
// clock. NOW() is generated by Postgres, whose container clock runs about a millisecond behind the
// host's, so `removedAt.Before(time.Now())` is a test that fails on timing.
func TestAccountRepository_MarkRemovedByLinkedItemID_LinkRemoved_Integration(t *testing.T) {
	pool := connectTestDB(t)
	enc := newTestFieldEncryptor(t)
	ctx := context.Background()
	profileRepo := NewProfileRepository(pool, enc)
	linkedItemRepo := NewLinkedItemRepository(pool, enc)
	accountRepo := NewAccountRepository(pool, enc)

	suffix := fmt.Sprintf("%d", time.Now().UnixNano())
	userID := createMarkDisconnectedFixtureUser(t, ctx, pool, profileRepo, suffix)
	item := createMarkDisconnectedFixtureItem(t, ctx, linkedItemRepo, userID, suffix)

	var accountID string
	require.NoError(t, pool.QueryRow(ctx, `
		INSERT INTO accounts (linked_item_id, user_id, plaid_account_id, name, type, current_balance)
		VALUES ($1, $2, $3, 'Swept Checking', 'depository', 4321.00)
		RETURNING id`,
		item.ID, userID, "plaid-linkremoved-"+suffix).Scan(&accountID))

	require.NoError(t, accountRepo.MarkRemovedByLinkedItemID(ctx, item.ID, domain.RemovalReasonLinkRemoved))

	var status string
	var removedAt *time.Time
	var reason *string
	require.NoError(t, pool.QueryRow(ctx,
		`SELECT status, removed_at, removed_reason FROM accounts WHERE id = $1`, accountID,
	).Scan(&status, &removedAt, &reason))

	assert.Equal(t, "removed", status)
	require.NotNil(t, removedAt, "removed_at must be stamped — it is what gives the UI its \"as of\" date")
	require.NotNil(t, reason)
	assert.Equal(t, "link_removed", *reason)
}

// The migration is load-bearing: 000154's predicate REJECTS 'link_removed'. Proven by re-imposing
// the old constraint inside a rolled-back transaction and observing the write fail, rather than by
// reading the migration file. Without this, "we widened the CHECK" is an unfalsified claim — the
// write would have succeeded either way if the column had never been constrained at all.
func TestAccountRepository_LinkRemoved_WasRejectedByThePre000167Constraint_Integration(t *testing.T) {
	pool := connectTestDB(t)
	enc := newTestFieldEncryptor(t)
	ctx := context.Background()
	profileRepo := NewProfileRepository(pool, enc)
	linkedItemRepo := NewLinkedItemRepository(pool, enc)

	// A REAL account row, created outside the probe transaction. An earlier draft of this test tried
	// `INSERT ... SELECT ... FROM linked_items LIMIT 1`, which inserted ZERO rows on a database with
	// no linked items and therefore violated nothing — the test passed while proving the opposite of
	// what it claimed. The row is created first, and its existence asserted, so the UPDATE below
	// cannot match nothing.
	suffix := fmt.Sprintf("%d", time.Now().UnixNano())
	userID := createMarkDisconnectedFixtureUser(t, ctx, pool, profileRepo, suffix)
	item := createMarkDisconnectedFixtureItem(t, ctx, linkedItemRepo, userID, suffix)

	var accountID string
	require.NoError(t, pool.QueryRow(ctx, `
		INSERT INTO accounts (linked_item_id, user_id, plaid_account_id, name, type)
		VALUES ($1, $2, $3, 'Constraint Probe', 'depository')
		RETURNING id`,
		item.ID, userID, "plaid-constraintprobe-"+suffix).Scan(&accountID))

	tx, err := pool.Begin(ctx)
	require.NoError(t, err)
	defer func() { _ = tx.Rollback(ctx) }() //nolint:errcheck // always rolled back

	_, err = tx.Exec(ctx, `ALTER TABLE accounts DROP CONSTRAINT accounts_removed_reason_valid`)
	require.NoError(t, err, "the constraint 000167 edits must exist under its documented name")
	_, err = tx.Exec(ctx, `
		ALTER TABLE accounts ADD CONSTRAINT accounts_removed_reason_valid
			CHECK (removed_reason IS NULL
			    OR (status = 'removed' AND removed_reason IN ('user_disconnect', 'provider_absent')))`)
	require.NoError(t, err)

	var admitted bool
	require.NoError(t, tx.QueryRow(ctx, `
		SELECT pg_get_constraintdef(oid) LIKE '%link_removed%'
		FROM pg_constraint WHERE conname = 'accounts_removed_reason_valid'`).Scan(&admitted))
	require.False(t, admitted, "sanity: the re-imposed 000154 predicate must not mention link_removed")

	// Control: 'user_disconnect' must still be accepted under the OLD predicate, so a failure below
	// is specifically about the new value and not about the probe having broken something else.
	ct, err := tx.Exec(ctx,
		`UPDATE accounts SET status = 'removed', removed_at = NOW(), removed_reason = 'user_disconnect' WHERE id = $1`,
		accountID)
	require.NoError(t, err)
	require.EqualValues(t, 1, ct.RowsAffected(), "the probe row must exist — a zero-row UPDATE violates nothing")

	_, err = tx.Exec(ctx,
		`UPDATE accounts SET removed_reason = 'link_removed' WHERE id = $1`, accountID)
	require.Error(t, err, "the pre-000167 constraint must reject 'link_removed' — if it does not, "+
		"migration 000167 is not what is admitting the value and this whole change is unfalsified")
	assert.Contains(t, err.Error(), "accounts_removed_reason_valid")
}

// 'link_removed' must NOT be auto-restorable. The bank still reports these accounts, so a later
// roster sync would happily resurrect them — under a Plaid Item that no longer exists — if the
// restore predicate were anything looser than an equality against 'provider_absent'.
func TestAccountRepository_RestoreAccount_RefusesLinkRemoved_Integration(t *testing.T) {
	pool := connectTestDB(t)
	enc := newTestFieldEncryptor(t)
	ctx := context.Background()
	profileRepo := NewProfileRepository(pool, enc)
	linkedItemRepo := NewLinkedItemRepository(pool, enc)
	accountRepo := NewAccountRepository(pool, enc)

	suffix := fmt.Sprintf("%d", time.Now().UnixNano())
	userID := createMarkDisconnectedFixtureUser(t, ctx, pool, profileRepo, suffix)
	item := createMarkDisconnectedFixtureItem(t, ctx, linkedItemRepo, userID, suffix)

	var accountID string
	require.NoError(t, pool.QueryRow(ctx, `
		INSERT INTO accounts (linked_item_id, user_id, plaid_account_id, name, type)
		VALUES ($1, $2, $3, 'Swept Savings', 'depository')
		RETURNING id`,
		item.ID, userID, "plaid-restoreprobe-"+suffix).Scan(&accountID))
	require.NoError(t, accountRepo.MarkRemovedByLinkedItemID(ctx, item.ID, domain.RemovalReasonLinkRemoved))

	err := accountRepo.RestoreProviderRemovedAccount(ctx, accountID, userID)
	require.Error(t, err, "a link_removed account must never be auto-restored")
	assert.ErrorIs(t, err, ErrAccountNotRestorable)

	var status string
	require.NoError(t, pool.QueryRow(ctx, `SELECT status FROM accounts WHERE id = $1`, accountID).Scan(&status))
	assert.Equal(t, "removed", status, "the refusal must leave the row removed, not half-restored")
}

// The repository refuses 'provider_absent' on this path outright, so a future caller cannot make
// its accounts resurrectable by passing the wrong constant. Asserted on the observable effect (no
// row changed) as well as on the error, because an error returned AFTER the UPDATE would be a
// refusal in name only.
func TestAccountRepository_MarkRemovedByLinkedItemID_RefusesProviderAbsent_Integration(t *testing.T) {
	pool := connectTestDB(t)
	enc := newTestFieldEncryptor(t)
	ctx := context.Background()
	profileRepo := NewProfileRepository(pool, enc)
	linkedItemRepo := NewLinkedItemRepository(pool, enc)
	accountRepo := NewAccountRepository(pool, enc)

	suffix := fmt.Sprintf("%d", time.Now().UnixNano())
	userID := createMarkDisconnectedFixtureUser(t, ctx, pool, profileRepo, suffix)
	item := createMarkDisconnectedFixtureItem(t, ctx, linkedItemRepo, userID, suffix)

	var accountID string
	require.NoError(t, pool.QueryRow(ctx, `
		INSERT INTO accounts (linked_item_id, user_id, plaid_account_id, name, type)
		VALUES ($1, $2, $3, 'Untouched', 'depository')
		RETURNING id`,
		item.ID, userID, "plaid-refuseprobe-"+suffix).Scan(&accountID))

	err := accountRepo.MarkRemovedByLinkedItemID(ctx, item.ID, domain.RemovalReasonProviderAbsent)
	require.Error(t, err)
	assert.Contains(t, err.Error(), "RestoreAccount will act on")

	var status string
	var reason *string
	require.NoError(t, pool.QueryRow(ctx,
		`SELECT status, removed_reason FROM accounts WHERE id = $1`, accountID).Scan(&status, &reason))
	assert.Equal(t, "active", status, "the refusal must happen before the UPDATE, not after it")
	assert.Nil(t, reason)
}
