// Package main generates backend/internal/domain/mcp_manifest_generated.go from
// apps/mcp-server/src/spec/generated/spec-index.json — the committed, CI-verified
// artifact that is itself built from apps/mcp-server/src/manifest/capability-manifest.ts
// (the TypeScript capability manifest, the real source of truth for MCP operation
// classification).
//
// Why generate instead of hand-maintaining a second copy (Issue #1610 P3-T6):
// the hand-maintained Go mirror in mcp_manifest.go drifted from the TS manifest —
// 22 read-class operations were simply never added, so valid read-only recipes for
// them were refused by recipe_service.go. A hand-maintained mirror with a drift *test*
// is still a hand-maintained mirror: someone has to remember to update it AND the test
// has to be run AND the failure has to be fixed. Generating the map removes the
// opportunity for the two sides to disagree at all.
//
// Usage: cd backend && go run scripts/generate-mcp-manifest/main.go
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// specEntry mirrors the fields of apps/mcp-server/src/spec/search-runtime.ts's SpecEntry
// that this generator needs. Other fields (method, path, parameters, ...) are ignored.
type specEntry struct {
	OperationID   string `json:"operationId"`
	ManifestClass string `json:"manifestClass"`
	Excluded      bool   `json:"excluded"`
}

type specIndex struct {
	Entries []specEntry `json:"entries"`
}

const goClassTemplate = `// Code generated by "cd backend && go run scripts/generate-mcp-manifest/main.go"
// from apps/mcp-server/src/spec/generated/spec-index.json. DO NOT EDIT.
//
// Regenerate after any change to apps/mcp-server/src/manifest/capability-manifest.ts
// (which requires first regenerating spec-index.json — see
// apps/mcp-server/src/spec/index-builder.ts). Verified fresh by
// TestMCPManifest_MatchesGeneratedFromSpecIndex and by "make validate-mcp-artifacts".
package domain

// MCPOperationManifest classifies every known operationId for the MCP server.
// Read-class operations may be used in v1 recipes (recipe_service.go); write and
// destructive operations are rejected by recipe validation; excluded operations are
// never reachable through MCP at all.
var MCPOperationManifest = map[string]MCPOperationClass{
%s}
`

func main() {
	// Path is relative to backend/, matching scripts/generate-openapi/main.go's convention
	// of being invoked as "cd backend && go run scripts/<name>/main.go".
	specPath := filepath.Join("..", "apps", "mcp-server", "src", "spec", "generated", "spec-index.json")

	data, err := os.ReadFile(specPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading %s: %v\n", specPath, err)
		fmt.Fprintln(os.Stderr, "Run 'cd apps/mcp-server && bun run src/spec/index-builder.ts' first.")
		os.Exit(1)
	}

	var idx specIndex
	if err := json.Unmarshal(data, &idx); err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing %s: %v\n", specPath, err)
		os.Exit(1)
	}

	if len(idx.Entries) == 0 {
		fmt.Fprintln(os.Stderr, "spec-index.json has no entries — refusing to generate an empty manifest")
		os.Exit(1)
	}

	sorted := make([]specEntry, len(idx.Entries))
	copy(sorted, idx.Entries)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].OperationID < sorted[j].OperationID })

	var b strings.Builder
	for _, e := range sorted {
		class, err := goClassFor(e)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error classifying %q: %v\n", e.OperationID, err)
			os.Exit(1)
		}
		fmt.Fprintf(&b, "\t%q: %s,\n", e.OperationID, class)
	}

	out := fmt.Sprintf(goClassTemplate, b.String())

	outPath := filepath.Join("internal", "domain", "mcp_manifest_generated.go")
	if err := os.WriteFile(outPath, []byte(out), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing %s: %v\n", outPath, err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s from %d spec-index entries.\n", outPath, len(sorted))
}

// goClassFor maps a spec-index entry to the Go MCPOperationClass constant name.
// An excluded op is always MCPClassExcluded regardless of its underlying TS class:
// Go's manifest only needs to know allow/deny plus read/not-read for recipe
// validation, so the finer-grained "excluded but was write" vs. "excluded but was
// destructive" distinction lives only in the TS manifest, which remains the audit
// trail of record.
func goClassFor(e specEntry) (string, error) {
	if e.Excluded {
		return "MCPClassExcluded", nil
	}
	switch e.ManifestClass {
	case "read":
		return "MCPClassRead", nil
	case "write":
		return "MCPClassWrite", nil
	case "destructive":
		return "MCPClassDestructive", nil
	default:
		return "", fmt.Errorf("unknown manifestClass %q", e.ManifestClass)
	}
}
