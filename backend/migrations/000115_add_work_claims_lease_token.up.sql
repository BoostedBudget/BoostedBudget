-- #1413: Add a fencing token to work_claims (Codex round-2 follow-up).
--
-- Closes the KNOWN LIMITATION documented in work_claims_repository.go: Complete
-- and Release previously identified a claim only by (resource_type, resource_id,
-- action) -- never by which lease INSTANCE Claim actually granted. When external
-- work runs longer than its lease (not crashed, just slow -- a GC pause, a hung
-- Plaid/Paddle call), another worker can legitimately reclaim and start the same
-- external work while the first worker is still mid-flight. The first worker's
-- eventual Complete/Release would then silently act on the reclaimer's lease
-- instead of erroring, so the record shows one execution when two happened.
--
-- lease_token is regenerated by Claim on every successful claim, including
-- reclaims of an expired lease. Complete/Release now require the caller's
-- token to match the row's current lease_token to have any effect, and report
-- whether it matched -- closing the gap instead of only mitigating it via
-- lease sizing.
--
-- work_claims has no production rows yet (added in 000114, not yet consumed by
-- any caller -- see the package doc comment in work_claims_repository.go), so
-- adding this NOT NULL column is safe with no backfill step. The DEFAULT
-- gen_random_uuid() is not a backfill mechanism -- work_claims.Claim always
-- supplies an explicit, freshly generated token itself -- it exists only so a
-- direct INSERT that omits lease_token (e.g. ad-hoc tooling) still gets a
-- syntactically valid UUID rather than failing NOT NULL. gen_random_uuid() is
-- already relied on elsewhere (000003_create_categories_table.up.sql) and is a
-- built-in function on PostgreSQL 13+, so no extension is required.
--
-- Idempotent: wrapped in a DO $$ block that checks column existence first.

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_name = 'work_claims'
          AND column_name = 'lease_token'
    ) THEN
        ALTER TABLE work_claims
            ADD COLUMN lease_token UUID NOT NULL DEFAULT gen_random_uuid();
    END IF;
END $$;

COMMENT ON COLUMN work_claims.lease_token IS
    'Fencing token for the CURRENT lease. Regenerated by Claim on every '
    'successful claim, including reclaims of an expired lease. Complete and '
    'Release require the caller''s token to match this value (AND '
    'lease_token = $n in their WHERE) to have any effect, and report whether '
    'it matched -- this is what prevents a worker whose external work outlived '
    'its lease from silently acting on a reclaimer''s lease. Part of #1413.';
